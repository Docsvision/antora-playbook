"use strict";
const fsp = require("node:fs/promises");
const path = require("node:path");

// Assembler prepares sources and commands. Only a separate make invocation converts PDFs.
module.exports.register = function ({ config = {} }) {
  const targets = new Map();
  let command, cwd, playbookDir;
  this.once("contextStarted", ({ playbook }) => { playbookDir = playbook.dir; });
  const converter = {
    backend: "pdf", extname: ".pdf", mediaType: "application/pdf",
    async convert(file, conversionAttributes, buildConfig) {
      const attrs = { ...conversionAttributes };
      Object.defineProperty(attrs, "toArgs", { value: conversionAttributes.toArgs });
      if (buildConfig.qualifyExports) {
        attrs.outfile = path.join(attrs.outdir, file.assembler.downloadStem + attrs.outfilesuffix);
      }
      cwd ??= buildConfig.cwd;
      command ??= buildConfig.command || "bundle exec asciidoctor-pdf";
      const target = relative(playbookDir, attrs.outfile);
      const source = relative(playbookDir, attrs.docfile);
      const outputArgument = relative(conversionAttributes.docdir, attrs.outfile);
      for (const [name, value] of Object.entries(attrs)) {
        // Paths in the playbook's directory move with it; text such as /usr/lib/docsvision stays as written.
        if (typeof value === "string" && value.startsWith(playbookDir + path.sep)) attrs[name] = relative(cwd, value);
      }
      const argv = attrs.toArgs("-a").concat("-B", attrs.docdir, "-o", outputArgument, attrs.docfile);
      targets.set(target, { source, argv });
      return null;
    },
  };
  this.require("@antora/assembler", { require }).configure(this, converter, config);
  this.once("sitePublished", async ({ playbook }) => {
    const lines = ["# Generated by Antora. PDF conversion is a separate step.", "SHELL := sh",
      "COMMAND := " + (command || "bundle exec asciidoctor-pdf").replaceAll("$", () => "$$"),
      ".PHONY: all", "all: " + [...targets.keys()].map(makePath).join(" "), ""];
    for (const [target, { source, argv }] of targets) {
      lines.push(makePath(target) + ": " + makePath(source));
      const cd = cwd && path.resolve(cwd) !== path.resolve(playbook.dir) ? "cd " + quote(relative(playbook.dir, cwd)) + " && " : "";
      lines.push("\t" + cd + "$(COMMAND) " + argv.map(quote).join(" "), "");
    }
    await fsp.writeFile(path.join(playbook.dir, "Makefile"), lines.join("\n"));
  });
};
function relative(cwd, value) { return path.relative(cwd, value).split(path.sep).join("/"); }
function makePath(value) { return value.replaceAll("$", () => "$$").replaceAll("#", "\\#").replaceAll(" ", "\\ "); }
function quote(value) { return "'" + String(value).replaceAll("'", "'\\''").replaceAll("$", () => "$$") + "'"; }


